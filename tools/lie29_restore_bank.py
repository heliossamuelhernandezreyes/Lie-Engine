"""Restore one small, attributed LIE28 brick capture into a standalone LIE29 bank.

This bank is not generated by image AI: it is a verbatim, SHA-verified subset of
the native Blender capture in LIE28-Assets-Maestros.zip. Only LOD1 (5,650
80-byte sample records) is shipped for this bounded first wall experiment.
"""
from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "gpu_compute/assets/lie29/brick_capture_bank.zlib.b64"
DESTINATION = ROOT / "gpu_compute/captures/lie29brick"
EXPECTED_SHA256 = "fbfd2fdba8ded34abeb0355c77004f77feba2c6dac4d3362b0d4125072bfe3d8"
SAMPLE_COUNT = 5650
STRIDE = 80


def restore(destination: Path = DESTINATION) -> Path:
    encoded = SOURCE.read_text(encoding="ascii")
    data = zlib.decompress(base64.b64decode("".join(encoded.split()), validate=True))
    if len(data) != SAMPLE_COUNT * STRIDE:
        raise ValueError("LIE29 capture bank byte count mismatch")
    if hashlib.sha256(data).hexdigest() != EXPECTED_SHA256:
        raise ValueError("LIE29 capture bank SHA-256 mismatch")
    destination.mkdir(parents=True, exist_ok=True)
    binary = destination / "library.bin"
    binary.write_bytes(data)
    catalog = {
        "schema": 1, "stride": STRIDE, "sample_count": SAMPLE_COUNT,
        "sha256": EXPECTED_SHA256, "bytes": len(data),
        "original_mesh_drawn": False,
        "source": "LIE28 original Blender-authored brick, captured with CC0 Factory Brick",
        "materials": [{"name": "Factory Brick", "creator": "Rob Tuytel",
                       "page": "https://polyhaven.com/a/factory_brick",
                       "license": "CC0-1.0"}],
        "masters": {
            "brick": {
                "levels": [{"start": 0, "count": SAMPLE_COUNT},
                           {"start": 0, "count": SAMPLE_COUNT}],
                "bounds_size": [0.24, 0.07, 0.12], "origin_offset": [0, 0, 0]
            }
        }
    }
    (destination / "catalog.json").write_text(
        json.dumps(catalog, sort_keys=True, separators=(",", ":")), encoding="utf-8"
    )
    return binary


if __name__ == "__main__":
    path = restore()
    print("Verified one-master brick capture:", path, path.stat().st_size, EXPECTED_SHA256)
