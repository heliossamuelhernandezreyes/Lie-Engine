"""Generate sparse kernel variants from the tested, unchanged dense equations.

Only factor addressing/iteration changes. Tests enforce derivation so future
physics fixes cannot silently diverge between dense and sparse backends.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "gpu_compute/shaders"
PAIRS = ("lie11_light_transport", "lie_wall04_transport")


def sparse_source(source: str) -> str:
    declaration = "readonly buffer Factors { float values[]; } factors;"
    loop = """for(uint source=0u;source<n;source++) {
            vec4 emitted=phase.data.y==0?frontier_a.values[source]:frontier_b.values[source];
            float weight=factors.values[source*n+i];"""
    replacement = """// Header: [patch count, edge count, offset base, edge base].
        // Rows belong to receivers; source IDs remain in ascending order.
        uint offset_base=factors.values[2], edge_base=factors.values[3];
        for(uint edge=factors.values[offset_base+i];edge<factors.values[offset_base+i+1u];edge++) {
            uint source=factors.values[edge_base+edge*2u];
            vec4 emitted=phase.data.y==0?frontier_a.values[source]:frontier_b.values[source];
            float weight=uintBitsToFloat(factors.values[edge_base+edge*2u+1u]);"""
    if source.count(declaration) != 1 or source.count(loop) != 1:
        raise ValueError("Dense transport changed: review sparse derivation")
    return source.replace("#version 450", "#version 450\n// Generated by tools/lie_sparse_shader.py; physics inherited from dense kernel.",1).replace(declaration,"readonly buffer Factors { uint values[]; } factors;").replace(loop,replacement)


if __name__ == "__main__":
    for name in PAIRS:
        (ROOT/(name+"_sparse.glsl")).write_text(sparse_source((ROOT/(name+".glsl")).read_text()))
